import type { NamePlacer, ReasonTexts } from "../reasons";

/**
 * Whether `name` ends in a consonant sound, which picks the particle after it: the final consonant of a Hangul
 * syllable, or for a name in Latin letters its last letter.
 */
function endsInConsonant(name: string): { consonant: boolean; rieul: boolean } {
  const code = name.charCodeAt(name.length - 1) - 0xac00;
  if (code >= 0 && code < 11172) {
    const final = code % 28;
    return { consonant: final !== 0, rieul: final === 8 };
  }
  const last = name.slice(-1).toLowerCase();
  return { consonant: /[a-z]/.test(last) && !"aeiouy".includes(last), rieul: last === "l" };
}

/** The particles the game's tags ask for after a name, without and with a final consonant. */
const PARTICLES: Readonly<Record<string, readonly [string, string]>> = {
  r: ["가", "이"],
  s: ["는", "은"],
  f: ["를", "을"],
  d: ["와", "과"],
  h: ["로", "으로"],
};

/** Puts the teammate's name in, with the particle `{name:r}`, `{name:f}` and the others ask for. */
export const placeNameKO: NamePlacer = (template, name) =>
  template.replace(/\{name(?::(\w+))?\}/g, (_, form?: string) => {
    const particles = form ? PARTICLES[form] : undefined;
    if (!particles) {
      return name;
    }
    const { consonant, rieul } = endsInConsonant(name);
    return name + (consonant && !(form === "h" && rieul) ? particles[1] : particles[0]);
  });

